import { contextBridge, ipcRenderer } from 'electron';

// Narrow, explicit API surface. Never expose ipcRenderer, Node, shell or arbitrary FS access.
contextBridge.exposeInMainWorld('safepeek', {
  getAppInfo: () => ipcRenderer.invoke('app:info'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (s: unknown) => ipcRenderer.invoke('settings:set', s),
  // Phase 2 monitoring
  getMonitoringStatus: () => ipcRenderer.invoke('monitor:status'),
  setMonitoringEnabled: (v: boolean) => ipcRenderer.invoke('monitor:setEnabled', v),
  addMonitoredFolder: () => ipcRenderer.invoke('monitor:addFolder'),
  removeMonitoredFolder: (id: string) => ipcRenderer.invoke('monitor:removeFolder', id),
  setFolderEnabled: (id: string, v: boolean) => ipcRenderer.invoke('monitor:setFolderEnabled', id, v),
  getDetectedFiles: () => ipcRenderer.invoke('monitor:files'),
  getRecentFileEvents: () => ipcRenderer.invoke('monitor:events'),
  reanalyzeFile: (id: string) => ipcRenderer.invoke('analysis:rerun', id),
  getContent: (id: string) => ipcRenderer.invoke('content:get', id),
  rerunContent: (id: string) => ipcRenderer.invoke('content:rerun', id),
  getThreat: (id: string) => ipcRenderer.invoke('threat:get', id),
  rerunThreat: (id: string) => ipcRenderer.invoke('threat:rerun', id),
  // Phase 6 (ids and booleans only; no paths)
  getProtectionStatus: () => ipcRenderer.invoke('protection:status'),
  getSecuritySettings: () => ipcRenderer.invoke('security:getSettings'),
  saveSecuritySettings: (p: unknown) => ipcRenderer.invoke('security:setSettings', p),
  getExplanation: (id: string) => ipcRenderer.invoke('explanation:get', id),
  getAiSettings: () => ipcRenderer.invoke('ai:getSettings'),
  saveAiSettings: (p: unknown) => ipcRenderer.invoke('ai:setSettings', p),
  setAiApiKey: (k: string) => ipcRenderer.invoke('ai:setApiKey', k),
  clearAiApiKey: () => ipcRenderer.invoke('ai:clearApiKey'),
  getAiDisclosure: (id: string) => ipcRenderer.invoke('ai:disclosure', id),
  requestAiExplanation: (id: string, confirmed: boolean) => ipcRenderer.invoke('ai:request', id, confirmed),
  listAlerts: (f?: unknown) => ipcRenderer.invoke('alerts:list', f),
  markAlertRead: (id: string) => ipcRenderer.invoke('alerts:markRead', id),
  markAllAlertsRead: () => ipcRenderer.invoke('alerts:markAllRead'),
  dismissAlert: (id: string) => ipcRenderer.invoke('alerts:dismiss', id),
  getThreatHistory: (limit?: number) => ipcRenderer.invoke('history:threats', limit),
  listQuarantine: () => ipcRenderer.invoke('quarantine:list'),
  quarantineFile: (fileId: string) => ipcRenderer.invoke('quarantine:add', fileId),
  restoreQuarantined: (id: string, confirmed: boolean, useFallback?: boolean) => ipcRenderer.invoke('quarantine:restore', id, confirmed, useFallback === true),
  deleteQuarantined: (id: string, confirmed: boolean) => ipcRenderer.invoke('quarantine:delete', id, confirmed),
  getOpenInfo: (id: string) => ipcRenderer.invoke('files:openInfo', id),
  openFile: (id: string, confirmed: boolean) => ipcRenderer.invoke('files:open', id, confirmed),
  openFileLocation: (id: string) => ipcRenderer.invoke('files:reveal', id),
  copyFilePath: (id: string) => ipcRenderer.invoke('files:copyPath', id),
  rescanFile: (id: string) => ipcRenderer.invoke('files:rescan', id),
  markFileReviewed: (id: string) => ipcRenderer.invoke('files:review', id),
  onNavigate: (cb: (t: { page: string; fileId?: string; alertId?: string }) => void) => { const h = (_e: unknown, t: { page: string; fileId?: string; alertId?: string }) => cb(t); ipcRenderer.on('app:navigate', h); return () => { ipcRenderer.removeListener('app:navigate', h); }; },
  createTestFile: () => ipcRenderer.invoke('monitor:createTestFile'),
  onChange: (cb: () => void) => { const h = () => cb(); ipcRenderer.on('agent:changed', h); return () => { ipcRenderer.removeListener('agent:changed', h); }; }
});
